// Regenerates examples/sample-outputs.md by running every script against a
// small SYNTHETIC library (invented titles/DOIs). Run: node tests/make-examples.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createEnv, runScript } from "./zotero-mock.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function demoLibrary(env) {
  const ann = (s, t, text, c) => ({ annotationSortIndex: s, annotationType: t, annotationText: text, annotationComment: c, annotationPageLabel: "4", annotationColor: "#ffd400" });
  env.item({ id: 901, itemType: "attachment", contentType: "application/pdf", fileExists: true,
    text: "Plants were grown at 28 °C day temperature. Nitrogen was applied at 240 kg N ha-1 with drip irrigation of 450 mm.",
    annotations: [ann("00001", "highlight", "Canopy light interception explained 78% of the variation in biomass.", "Compare with our ray-tracing results")] });
  env.item({ id: 902, itemType: "attachment", contentType: "application/pdf", fileExists: false, text: "" });
  return [
    env.item({ id: 1, fields: { title: "Deep learning for cotton yield prediction from UAV imagery", date: "2024-03-01", publicationTitle: "Demo Journal of Crop Science", DOI: "https://doi.org/10.9999/demo.2024.001", abstractNote: "We trained a convolutional neural network on UAV multispectral images to support yield prediction for cotton.", volume: "12", pages: "101" },
      creators: [{ lastName: "Zhang", firstName: "A." }], tags: ["Remote sensing", "UAV"], attachments: [901] }),
    env.item({ id: 2, fields: { title: "Deep Learning for Cotton Yield Prediction from UAV Imagery.", date: "March 2024", publicationTitle: "Demo Journal of Crop Science", DOI: "doi:10.9999/DEMO.2024.001", abstractNote: "Duplicate record of the same paper." },
      creators: [{ lastName: "Zhang", firstName: "A." }], tags: ["remote-sensing"] }),
    env.item({ id: 3, fields: { title: "A review of 3D canopy reconstruction and ray tracing for photosynthesis modelling", date: "2022", publicationTitle: "Demo Plant Phenomics", abstractNote: "Review of point cloud, structure from motion and ray tracing methods for canopy photosynthesis.", DOI: "10.9999/demo.2022.017" },
      creators: [{ lastName: "Wang", firstName: "B." }], attachments: [902] }),
    env.item({ id: 4, fields: { title: "Random forest regression of wheat LAI from Sentinel-2", date: "2019-07", publicationTitle: "Demo Remote Sensing Letters", abstractNote: "Random forest and linear model baselines for LAI retrieval; ANOVA across sites." },
      creators: [{ lastName: "Li", firstName: "C." }] })
  ];
}

const cases = [
  ["01-literature-management/01-metadata-completeness-check.js", {}],
  ["01-literature-management/02-duplicate-candidates-finder.js", {}],
  ["01-literature-management/03-doi-cleanup-preview.js", {}],
  ["01-literature-management/04-rule-based-auto-tagging.js", {}],
  ["01-literature-management/05-doi-batch-fix-confirm.js", {}, "Dialog answered with Cancel / 对话框选择“取消”"],
  ["02-research-productivity/06-llm-review-prompt-builder.js", {}],
  ["02-research-productivity/07-pdf-attachment-health-check.js", {}],
  ["02-research-productivity/08-reference-quality-check.js", {}],
  ["02-research-productivity/09-annotation-export-markdown.js", {}],
  ["02-research-productivity/10-review-matrix-markdown.js", {}],
  ["02-research-productivity/11-similar-tags-check.js", {}],
  ["03-research-mining/12-pdf-keyword-context-search.js", {}],
  ["03-research-mining/13-title-abstract-screening-csv.js", {}],
  ["03-research-mining/14-topic-trend-by-year-csv.js", {}]
];

const out = [
  "# Sample outputs / 示例输出",
  "",
  "[Back to README](../README.md) · [返回中文 README](../README.zh-CN.md)",
  "",
  "Generated by `node tests/make-examples.mjs` from a **synthetic 4-item demo library** (invented titles and DOIs, run against the mock Zotero API). Output language: Chinese (default `LANG`). In Zotero, the same text appears in the Run JavaScript result pane.",
  "",
  "由 `node tests/make-examples.mjs` 基于**虚构的 4 条示例文献**（标题与 DOI 均为虚构，在模拟 Zotero API 中运行）生成，默认中文输出。在 Zotero 中，这些文本显示于 Run JavaScript 的结果窗格。",
  ""
];

for (const [rel, repl, note] of cases) {
  const env = createEnv({ confirmIndex: 1 });
  env.registry.selected = demoLibrary(env);
  const result = await runScript(path.join(ROOT, "scripts", rel), env, repl);
  out.push(`## ${path.basename(rel)}`, "");
  if (note) out.push(`_${note}_`, "");
  out.push("```text", String(result).slice(0, 3000), "```", "");
  if (rel.includes("13-title-abstract")) {
    out.push("Clipboard (CSV) / 剪贴板内容（CSV）:", "", "```csv", env.registry.clipboard, "```", "");
  }
}

fs.writeFileSync(path.join(ROOT, "examples", "sample-outputs.md"), out.join("\n"));
console.log("wrote examples/sample-outputs.md");
